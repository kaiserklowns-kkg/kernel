/// The services of a real machine, from `config/services.conf`: the same
/// system, but the root filesystem lives on the NVMe SSD (formatted only if
/// its start is blank, else left untouched and files kept in memory), not
/// on a virtio disk. A SATA disk stays where `services.conf` puts it, at
/// /sata (ADR-0069). Generated, never kept as a copy: each change below
/// must find exactly what it changes.
pub fn hardware_services(text: &str) -> Result<String> {
    let mut text = remove_service(text, "block")?;
    for (from, to) in [
        ("    use = block\n", "    use = nvme as block\n"),
        // The NVMe SSD's EFI system partition when Oceans started from it
        // (an installed system, ADR-0126), as `/boot`.
        (
            "service nvmefs\n    image = fs\n    restart = always\n    grant = log\n    \
             provide = nvmefs\n    use = nvme as block\n",
            "service nvmeboot\n    image = fs\n    restart = always\n    grant = log\n    \
             grant = sysinfo\n    provide = nvmeboot\n    use = nvme as boot\n",
        ),
        (
            "    use = nvmefs as mount:nvme\n",
            "    use = nvmeboot as mount:boot\n",
        ),
    ] {
        if text.matches(from).count() != 1 {
            return Err(format!(
                "services.conf: cannot make the hardware profile (`{}` must appear once)",
                from.trim()
            ));
        }
        text = text.replacen(from, to, 1);
    }
    Ok(format!(
        "# The hardware profile (ADR-0068), generated by `cargo xtask` from\n\
         # config/services.conf: the root filesystem on the NVMe SSD (its\n\
         # Oceans partition when installed, ADR-0126), its EFI system\n\
         # partition as /boot.\n\n{text}"
    ))
}

/// `text` without the stanza `service NAME` (to the next blank line).
fn remove_service(text: &str, name: &str) -> Result<String> {
    let header = format!("service {name}\n");
    let start = text
        .match_indices(&header)
        .find(|(at, _)| *at == 0 || text.as_bytes()[at - 1] == b'\n')
        .map(|(at, _)| at)
        .ok_or(format!("services.conf has no `service {name}`"))?;
    let end = text[start..]
        .find("\n\n")
        .map_or(text.len(), |len| start + len + 2);
    Ok(format!("{}{}", &text[..start], &text[end..]))
}

/// `cargo xtask usb`: the image to write to a USB stick for a real machine
/// (the hardware profile).
pub fn usb(profile: Profile) -> Result {
    let esp = build_image_for(
        profile,
        None,
        Setup::Hardware,
        &release::ImageKeys::development()?,
    )?;
    write_usb_image(&esp)?;
    println!(
        "{USB_IMAGE} is a development image: it trusts the development key, whose seed is \
         public (`cargo xtask release` builds one that trusts only a release key, ADR-0072)"
    );
    println!(
        "{USB_IMAGE} is ready: write it to a USB stick (Rufus, dd, balenaEtcher) and boot a \
         UEFI machine from it (docs/hardware/compatibility.md)"
    );
    Ok(())
}

/// `cargo xtask usb-secure-boot`: the same image, signed for Secure Boot
/// with the development Secure Boot key (ADR-0091).
pub fn usb_secure_boot(profile: Profile) -> Result {
    let esp = build_image_for(
        profile,
        None,
        Setup::Hardware,
        &release::ImageKeys::development()?,
    )?;
    let key = crate::secure_boot::development_key()?;
    crate::secure_boot::write_secure_usb_image(&esp, &key)?;
    println!(
        "{USB_IMAGE} is signed for Secure Boot with the development Secure Boot key: enrol \
         tools/keys/oceans-dev-secure-boot.cer (on the stick, {}) in the firmware's db to boot \
         it with Secure Boot on",
        crate::secure_boot::CERTIFICATE_FILE
    );
    Ok(())
}

/// Packs `esp` into [`USB_IMAGE`]: GPT, one EFI system partition with
/// FAT32 holding its files (made here, ADR-0092).
pub fn write_usb_image(esp: &Path) -> Result {
    let used = disk_image::tree_size(esp)?;
    // Room for the second slot and an update file beside it (ADR-0071).
    let esp_mib = (used / (1 << 20) * 3 + 48).max(64);
    let kernel = fs::read(esp.join("boot").join("a").join(KERNEL_PACKAGE)).unwrap_or_default();
    let mut sources = vec![esp.join("EFI"), esp.join("boot"), esp.join("limine.conf")];
    // A Secure Boot image's certificate, at the root (ADR-0091).
    let certificate = esp.join(crate::secure_boot::CERTIFICATE_FILE);
    if certificate.is_file() {
        sources.push(certificate);
    }
    disk_image::gpt_image(
        &root().join(USB_IMAGE),
        &[disk_image::Volume {
            kind: oceans_gpt::EFI_SYSTEM,
            name: "EFI system partition",
            label: "OCEANS",
            mib: esp_mib,
            sources,
        }],
        &kernel,
    )?;
    println!(
        "{USB_IMAGE}: GPT, an EFI system partition of {esp_mib} MiB ({} MiB of files)",
        used >> 20
    );
    Ok(())
}

/// An installed system's disk (ADR-0126) at `path`: GPT, the EFI system
/// partition holding what the USB image holds (`esp`), then a blank Oceans
/// root of `INSTALLED_ROOT_MIB`, formatted at first boot.
pub fn write_installed_image(esp: &Path, path: &str) -> Result {
    let used = disk_image::tree_size(esp)?;
    let esp_mib = (used / (1 << 20) * 3 + 48).max(64);
    let kernel = fs::read(esp.join("boot").join("a").join(KERNEL_PACKAGE)).unwrap_or_default();
    disk_image::gpt_image(
        &root().join(path),
        &[
            disk_image::Volume {
                kind: oceans_gpt::EFI_SYSTEM,
                name: "EFI system partition",
                label: "OCEANS",
                mib: esp_mib,
                sources: vec![esp.join("EFI"), esp.join("boot"), esp.join("limine.conf")],
            },
            disk_image::Volume {
                kind: oceans_gpt::OCEANS_ROOT,
                name: "Oceans",
                label: "",
                mib: INSTALLED_ROOT_MIB,
                sources: Vec::new(),
            },
        ],
        // GUIDs of its own: never those of the USB image, whose EFI system
        // partition `/boot` must not mistake for this one.
        &[kernel.as_slice(), b"installed"].concat(),
    )
}

/// The installed root in the hardware smoke test.
const INSTALLED_ROOT_MIB: u64 = 64;

/// The hardware image's boot partition (ADR-0071): the release in slot
/// `boot/a`, and Limine's configuration in both places it looks
/// (`/limine.conf` first, then `/boot/limine/limine.conf`).
pub fn slot_layout(esp: &Path, release: &str) -> Result {
    let boot = esp.join("boot");
    let slot = boot.join("a");
    fs::create_dir_all(&slot).map_err(|e| format!("cannot create {}: {e}", slot.display()))?;
    for name in [KERNEL_PACKAGE, "initrd"] {
        fs::rename(boot.join(name), slot.join(name))
            .map_err(|e| format!("cannot move {name} into slot a: {e}"))?;
    }
    fs::write(slot.join("release"), format!("{release}\n"))
        .map_err(|e| format!("cannot write the release: {e}"))?;
    let entries = release_entries(&format!("Oceans {release}"), 'a');
    let entries: Vec<(&str, char, &str)> = entries
        .iter()
        .map(|(n, s, c)| (n.as_str(), *s, *c))
        .collect();
    let conf = boot_configuration(&entries);
    for path in [
        esp.join("limine.conf"),
        boot.join("limine").join("limine.conf"),
    ] {
        fs::write(&path, &conf).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    }
    Ok(())
}

/// Limine's configuration for the slots, first entry first, each with
/// its kernel command line (empty, or a boot mode: ADR-0122): the same text
/// `update` writes (user/utils/src/bin/update/main.rs).
fn boot_configuration(entries: &[(&str, char, &str)]) -> String {
    let mut conf = String::from(
        "# Oceans boot configuration (ADR-0071), written by `update`.\ntimeout: 3\n\n",
    );
    for (i, (name, slot, cmdline)) in entries.iter().enumerate() {
        if i > 0 {
            conf.push('\n');
        }
        let cmdline = if cmdline.is_empty() {
            String::new()
        } else {
            format!("    cmdline: {cmdline}\n")
        };
        conf.push_str(&format!(
            "/{name}\n    protocol: limine\n    path: boot():/boot/{slot}/{KERNEL_PACKAGE}\n\
             {cmdline}    module_path: boot():/boot/{slot}/initrd\n"
        ));
    }
    conf
}

/// The entries for a release in `slot` (ADR-0122): the usual system, then
/// the same in safe mode and in recovery mode.
fn release_entries(name: &str, slot: char) -> [(String, char, &'static str); 3] {
    [
        (name.to_string(), slot, ""),
        (format!("{name} (safe mode)"), slot, "oceans.mode=safe"),
        (format!("{name} (recovery)"), slot, "oceans.mode=recovery"),
    ]
}

/// A system update (ADR-0071): this image's kernel and boot archive as
/// release `version`, signed with `key`.
pub fn system_package(
    esp: &Path,
    version: &str,
    key: &oceans_dev::DeveloperKey,
    description: &str,
    secure_boot: Option<&oceans_dev::secure_boot::SecureBootKey>,
) -> Result<Vec<u8>> {
    let slot = esp.join("boot").join("a");
    let kernel = fs::read(slot.join(KERNEL_PACKAGE)).map_err(|e| format!("kernel: {e}"))?;
    let initrd = fs::read(slot.join("initrd")).map_err(|e| format!("initrd: {e}"))?;
    let archive = oceans_archive::Archive::parse(&initrd)
        .map_err(|e| format!("the boot archive does not parse: {e:?}"))?;
    let release = format!("{version} {RELEASE_CHANNEL}\n");
    let entries: Vec<(&str, &[u8])> = archive
        .files()
        .map(|file| {
            if file.name == "release" {
                (file.name, release.as_bytes())
            } else {
                (file.name, file.data)
            }
        })
        .collect();
    let mut new_initrd = vec![0u8; oceans_archive::archive_len(&entries)];
    oceans_archive::write(&entries, &mut new_initrd)
        .map_err(|e| format!("cannot build the boot archive: {e:?}"))?;
    let manifest = format!(
        "id = system.oceans\nname = Oceans\nversion = {version}\npublisher = {}\n\
         description = {description}\narchitecture = x86_64\n\
         api = 1\nchannel = {RELEASE_CHANNEL}\nentry = {KERNEL_PACKAGE}\n",
        key.publisher
    );
    // For systems that boot with Secure Boot (ADR-0092): the slot's signed
    // Limine and its configuration, naming this kernel and boot archive.
    let boot_files = match secure_boot {
        Some(sb_key) => Some(crate::secure_boot::slot_boot_files(
            release.trim(),
            &kernel,
            &new_initrd,
            sb_key,
        )?),
        None => None,
    };
    // Limine as the slot boots it, for the installer (ADR-0127): an
    // installed disk gets it from the verified package.
    let limine = fs::read(esp.join("EFI").join("BOOT").join("BOOTX64.EFI"))
        .map_err(|e| format!("Limine: {e}"))?;
    let mut files: Vec<(&str, &[u8])> = vec![
        ("manifest", manifest.as_bytes()),
        (KERNEL_PACKAGE, &kernel),
        ("initrd", &new_initrd),
        ("limine.efi", &limine),
    ];
    if let Some((efi, config)) = &boot_files {
        files.push((crate::secure_boot::UPDATE_EFI, efi));
        files.push((crate::secure_boot::UPDATE_CONFIG, config.as_bytes()));
    }
    oceans_package::build(&files, &key.seed).map_err(|e| format!("cannot sign the update: {e:?}"))
}

/// The hardware smoke test's system packages:
/// - an update signed with its release key;
/// - one signed with the development key, which a release image does not
///   trust (refused before its files are looked at: placeholders keep it
///   small);
/// - a small one signed with the release key (the kernel, a placeholder
///   boot archive), for `app install` to refuse (ADR-0073): the update
///   itself is larger than the shell's limit for packages.
fn smoke_updates(esp: &Path) -> Result<(Vec<u8>, Vec<u8>, Vec<u8>)> {
    let update = system_package(
        esp,
        "0.1.1",
        &release::test_release_key(),
        "A system update (the hardware smoke test's)",
        None,
    )?;
    let manifest = format!(
        "id = system.oceans\nname = Oceans\nversion = 0.1.1\npublisher = {DEV_PUBLISHER}\n\
         architecture = x86_64\napi = 1\nentry = {KERNEL_PACKAGE}\n"
    );
    let placeholder: [(&str, &[u8]); 3] = [
        ("manifest", manifest.as_bytes()),
        (KERNEL_PACKAGE, b"placeholder"),
        ("initrd", b"placeholder"),
    ];
    let untrusted = oceans_package::build(&placeholder, &dev_seed()?)
        .map_err(|e| format!("cannot sign: {e:?}"))?;
    let key = release::test_release_key();
    let manifest = format!(
        "id = system.oceans\nname = Oceans\nversion = 0.1.2\npublisher = {}\n\
         architecture = x86_64\napi = 1\nentry = {KERNEL_PACKAGE}\n",
        key.publisher
    );
    let kernel = fs::read(esp.join("boot").join("a").join(KERNEL_PACKAGE))
        .map_err(|e| format!("kernel: {e}"))?;
    let small: [(&str, &[u8]); 3] = [
        ("manifest", manifest.as_bytes()),
        (KERNEL_PACKAGE, &kernel),
        ("initrd", b"placeholder"),
    ];
    let system =
        oceans_package::build(&small, &key.seed).map_err(|e| format!("cannot sign: {e:?}"))?;
    Ok((update, untrusted, system))
}

/// Copies `files` (name, bytes) to the root of [`USB_IMAGE`]'s partition.
fn copy_to_usb(files: &[(&str, &[u8])]) -> Result {
    let mut fat = disk_image::open_partition(&root().join(USB_IMAGE), 1)?;
    for (name, bytes) in files {
        disk_image::put_file(&mut fat, oceans_fat::ROOT, name, bytes)?;
    }
    fat.sync().map_err(|e| format!("{USB_IMAGE}: {e:?}"))
}

