/// One boot of the USB image: the shell (on the serial line) gets each
/// script line at a prompt; the boot passes when every expectation is met.
/// A script ending with `reboot` or `shutdown` (ADR-0085) must make QEMU
/// exit by itself (`-no-reboot`), cleanly, with no power fallback used.
/// Where a hardware boot starts: the USB stick, or the NVMe SSD (an
/// installed system, ADR-0126; the stick still plugged in).
#[derive(Clone, Copy, PartialEq, Eq)]
enum BootFrom {
    Stick,
    Nvme,
}

fn hw_boot(script: &[&[u8]], expected: &[Expect], from: BootFrom) -> Result {
    let (nvme_index, stick_index) = match from {
        BootFrom::Stick => (1, 0),
        BootFrom::Nvme => (0, 1),
    };
    let qemu = find_qemu()?;
    let firmware = find_firmware(&qemu)?;
    let mut pflash = std::ffi::OsString::from("if=pflash,format=raw,readonly=on,file=");
    pflash.push(&firmware);
    let monitor_port = free_tcp_port()?;
    let serial_port = free_tcp_port()?;
    let mut child = Command::new(&qemu)
        .current_dir(root())
        // A Tier 1 machine (ADR-0005): x86-64-v2 or newer.
        .args(["-machine", "q35", "-cpu", "max", "-m", "512M", "-no-reboot"])
        // A four-core PC (ADR-0088).
        .args(["-smp", "4"])
        .args(serial_args(Some(serial_port)))
        .args(["-display", "none"])
        .arg("-drive")
        .arg(pflash)
        // No virtio anywhere: what a PC has.
        .arg("-drive")
        .arg(format!("if=none,id=nvme0,format=raw,file={HW_NVME_IMAGE}"))
        .arg("-device")
        .arg(format!(
            "nvme,serial=oceans-hw,drive=nvme0,bootindex={nvme_index}"
        ))
        // A SATA disk on q35's AHCI controller (its buses are ide.0 to
        // ide.5, one per port): port 0.
        .arg("-drive")
        .arg(format!("if=none,id=sata0,format=raw,file={HW_SATA_IMAGE}"))
        .args(["-device", "ide-hd,drive=sata0,bus=ide.0,serial=oceans-sata"])
        .args(["-netdev", "user,id=net0", "-device", "e1000e,netdev=net0"])
        // The monitor: where each CPU is, if the boot hangs.
        .arg("-monitor")
        .arg(format!("tcp:127.0.0.1:{monitor_port},server=on,wait=off"))
        .args([
            "-device",
            "qemu-xhci,id=usb",
            "-device",
            "usb-kbd,bus=usb.0,port=1",
        ])
        .arg("-drive")
        .arg(format!("if=none,id=stick,format=raw,file={USB_IMAGE}"))
        .arg("-device")
        .arg(format!(
            "usb-storage,bus=usb.0,port=2,drive=stick,bootindex={stick_index}"
        ))
        // HD Audio, as on every PC (ADR-0079), recorded.
        .arg("-audiodev")
        .arg(audiodev(true, "build/smoke-hw-audio.wav"))
        .args([
            "-device",
            "intel-hda",
            "-device",
            "hda-output,audiodev=snd0",
        ])
        // And a microphone, as on most PCs (ADR-0087).
        .arg("-audiodev")
        .arg(input_audiodev(true))
        .args(["-device", "hda-micro,audiodev=snd1,cad=1"])
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .spawn()
        .map_err(|e| format!("failed to start QEMU: {e}"))?;
    let stdout = connect_serial(&mut child, serial_port)?;
    let mut input = stdout
        .try_clone()
        .map_err(|e| format!("the serial line: {e}"))?;
    let (lines_tx, lines) = mpsc::channel::<std::result::Result<String, ()>>();
    thread::spawn(move || {
        let mut reader = BufReader::new(stdout);
        let mut line = Vec::new();
        let mut rejoin = super::Rejoin::default();
        while let Ok(buffer) = reader.fill_buf() {
            if buffer.is_empty() {
                break;
            }
            let (consumed, prompt) = {
                let mut consumed = 0;
                let mut prompt = false;
                for &byte in buffer {
                    consumed += 1;
                    if byte == b'\n' {
                        let _ = lines_tx.send(Ok(rejoin.push(&String::from_utf8_lossy(&line))));
                        line.clear();
                    } else {
                        line.push(byte);
                        if line.ends_with(SHELL_PROMPT) {
                            prompt = true;
                            break;
                        }
                    }
                }
                (consumed, prompt)
            };
            reader.consume(consumed);
            if prompt {
                let _ = lines_tx.send(Err(()));
            }
        }
    });

    let deadline = Instant::now() + HW_TIMEOUT;
    let mut unmet: Vec<Expect> = expected.to_vec();
    let mut commands = script.iter();
    let ends_with_power = script
        .last()
        .is_some_and(|last| matches!(*last, b"reboot\r\n" | b"shutdown\r\n"));
    // A boot without a shell (install mode, ADR-0127) ends by itself.
    let mut power_sent = script.is_empty();
    let mut done_at: Option<Instant> = None;
    let outcome = loop {
        if let Some(at) = done_at
            && Instant::now() >= at
        {
            break Ok(());
        }
        let wait = deadline.saturating_duration_since(Instant::now());
        let wait = done_at.map_or(wait, |at| {
            wait.min(at.saturating_duration_since(Instant::now()))
        });
        match lines.recv_timeout(wait) {
            Ok(Ok(line)) => {
                println!("  | {line}");
                if line.contains("KERNEL PANIC") {
                    break Err(format!("the kernel panicked: {line}"));
                }
                // The ACPI way failed and a fallback ran (ADR-0085).
                if line.contains("power: the ") || line.contains("power: forcing") {
                    break Err(format!("switching off or restarting failed: {line}"));
                }
                unmet.retain(|expect| !expect.matches(&line));
            }
            // A prompt: the next command, or (all sent) a moment for the
            // last output, then done.
            Ok(Err(())) => match commands.next() {
                Some(command) => {
                    for &byte in *command {
                        let _ = input.write_all(&[byte]).and_then(|()| input.flush());
                        thread::sleep(Duration::from_millis(5));
                    }
                    power_sent = ends_with_power && commands.len() == 0;
                }
                None => {
                    done_at.get_or_insert(Instant::now() + Duration::from_secs(2));
                }
            },
            Err(mpsc::RecvTimeoutError::Timeout) if done_at.is_some() => break Ok(()),
            Err(mpsc::RecvTimeoutError::Timeout) => {
                // What every thread waits on (the kernel's diagnostic key,
                // Ctrl+\), for a hang to be found afterwards.
                let _ = input.write_all(&[0x1c]).and_then(|()| input.flush());
                let until = Instant::now() + Duration::from_secs(3);
                while let Ok(Ok(line)) =
                    lines.recv_timeout(until.saturating_duration_since(Instant::now()))
                {
                    println!("  | {line}");
                }
                report_cpus(monitor_port);
                break Err(format!(
                    "hardware smoke boot timed out after {}s",
                    HW_TIMEOUT.as_secs()
                ));
            }
            // Switched off or restarted: QEMU ends by itself.
            Err(mpsc::RecvTimeoutError::Disconnected) if power_sent => break Ok(()),
            Err(mpsc::RecvTimeoutError::Disconnected) => break Err("QEMU exited".into()),
        }
    };
    if power_sent && outcome.is_ok() {
        let status = child.wait().map_err(|e| format!("waiting for QEMU: {e}"))?;
        if !status.success() {
            return Err(format!("QEMU ended with {status} after the power request"));
        }
    } else {
        // The hardware profile has no test exit: the boot ends here.
        let _ = child.kill();
        let _ = child.wait();
    }
    outcome?;
    if !unmet.is_empty() {
        return Err(format!("hardware boot output missing: {unmet:?}"));
    }
    Ok(())
}

