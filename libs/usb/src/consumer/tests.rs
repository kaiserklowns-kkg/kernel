extern crate std;

use std::vec::Vec;

use super::*;

/// Seven keys as bits, in report 2 (as many keyboards' second interface
/// sends them), after a keyboard collection in report 1.
const BITS: &[u8] = &[
    0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, // Generic Desktop, Keyboard
    0x85, 0x01, 0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7, 0x15, 0x00, 0x25, 0x01, //
    0x75, 0x01, 0x95, 0x08, 0x81, 0x02, // modifiers
    0xc0, //
    0x05, 0x0c, 0x09, 0x01, 0xa1, 0x01, // Consumer, Consumer Control
    0x85, 0x02, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x07, //
    0x09, 0xe9, 0x09, 0xea, 0x09, 0xe2, 0x09, 0xcd, 0x09, 0xb5, 0x09, 0xb6, 0x09, 0xb7, //
    0x81, 0x02, // the keys
    0x95, 0x01, 0x81, 0x01, // padding
    0xc0,
];

/// One 16-bit value naming any consumer usage, in report 3 (an array).
const ARRAY: &[u8] = &[
    0x05, 0x0c, 0x09, 0x01, 0xa1, 0x01, //
    0x85, 0x03, 0x15, 0x00, 0x26, 0xff, 0x03, 0x19, 0x00, 0x2a, 0xff, 0x03, //
    0x75, 0x10, 0x95, 0x02, 0x81, 0x00, // two slots
    0xc0,
];

fn typed(layout: Layout, reports: &[&[u8]]) -> Vec<u8> {
    let mut keys = Keys::new(layout);
    let mut out = Vec::new();
    for report in reports {
        keys.report(report, |byte| out.push(byte));
    }
    out
}

#[test]
fn keys_as_bits_after_a_keyboard_report() {
    let layout = Layout::parse(BITS).unwrap();
    assert_eq!(layout.report_id, Some(2));
    let out = typed(
        layout,
        &[
            &[0x02, 0b0000_0001], // Volume Up
            &[0x02, 0b0000_0001], // held: nothing more
            &[0x01, 0xff],        // the keyboard's report: ignored
            &[0x02, 0b0000_1110], // Down, Mute, Play/Pause
            &[0x02, 0],
            &[0x02, 0b0111_0000], // Next, Previous, Stop
            &[0x02],              // short: nothing
        ],
    );
    assert_eq!(out, [0x8e, 0x8c, 0x8d, 0xa0, 0xa1, 0xa2, 0xa3]);
}

#[test]
fn keys_as_values_of_an_array() {
    let layout = Layout::parse(ARRAY).unwrap();
    assert_eq!(layout.report_id, Some(3));
    let out = typed(
        layout,
        &[
            &[0x03, 0xcd, 0x00, 0x00, 0x00], // Play/Pause
            &[0x03, 0xcd, 0x00, 0xe2, 0x00], // and Mute, Play/Pause held
            &[0x03, 0x00, 0x00, 0x00, 0x00],
            &[0x03, 0x23, 0x02, 0x00, 0x00], // AC Home: not a key here
            &[0x03, 0xb5, 0x00, 0x00, 0x00], // Next
        ],
    );
    assert_eq!(out, [0xa0, 0x8c, 0xa3]);
}

#[test]
fn descriptors_without_known_keys_or_whole_are_refused() {
    // A Consumer Control collection with only AC Pan.
    let pan = [
        0x05, 0x0c, 0x09, 0x01, 0xa1, 0x01, 0x0a, 0x38, 0x02, 0x15, 0x81, 0x25, 0x7f, 0x75,
        0x08, 0x95, 0x01, 0x81, 0x06, 0xc0,
    ];
    assert_eq!(Layout::parse(&pan), Err(Error::NoKeys));
    // A mouse.
    let mouse = [
        0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00,
        0x25, 0x01, 0x75, 0x01, 0x95, 0x03, 0x81, 0x02, 0xc0,
    ];
    assert_eq!(Layout::parse(&mouse), Err(Error::NoKeys));
    // Cut short, and a collection never closed.
    assert_eq!(Layout::parse(&BITS[..BITS.len() - 3]), Err(Error::Malformed));
    assert_eq!(Layout::parse(&[0x05]), Err(Error::Malformed));
}

#[test]
fn bytes_are_the_keyboards() {
    let bytes: Vec<u8> = Key::ALL.iter().map(|k| k.byte()).collect();
    assert_eq!(bytes, [0x8c, 0x8d, 0x8e, 0xa0, 0xa1, 0xa2, 0xa3]);
    assert_eq!(Key::of(0x000c_00e9), Some(Key::VolumeUp));
    assert_eq!(Key::of(0x0007_00e9), None);
}
